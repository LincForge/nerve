"""Generate tool-count + tool-table docs sections from the registration decorators.

Single-sources the MCP tool surface into the docs (issue #81: README said 40,
LINC.md said 38, the workspace LINC.md said 36 — the registry said 41). Two
kinds of generated regions, same pattern as the ARCH:AUTO blocks:

- Block:  ``<!-- NERVE:TOOLS-AUTO-START ... -->`` … ``<!-- NERVE:TOOLS-AUTO-END -->``
  — replaced with a generated "## MCP Tools (N)" section + per-category table.
- Inline: ``<!-- NERVE:TOOL-COUNT -->N<!-- /NERVE:TOOL-COUNT -->``
  — the count between the markers is rewritten (HTML comments render
  invisibly, so prose like "exposes N MCP tools" stays readable).

Usage:
    uv run python -m linc_nerve.docs_gen           # rewrite stale files
    uv run python -m linc_nerve.docs_gen --check   # exit 1 if stale (CI)

``tests/test_docs_sync.py`` runs the check in CI, so a tool added without
regenerating the docs fails the build.
"""

from __future__ import annotations

import asyncio
import importlib
import pathlib
import re
import sys

BLOCK_START = (
    "<!-- NERVE:TOOLS-AUTO-START — generated by `python -m linc_nerve.docs_gen`, do not edit -->"
)
BLOCK_END = "<!-- NERVE:TOOLS-AUTO-END -->"
COUNT_START = "<!-- NERVE:TOOL-COUNT -->"
COUNT_END = "<!-- /NERVE:TOOL-COUNT -->"

# Files (relative to repo root) that carry generated regions.
# CLAUDE.md / ANTIGRAVITY.md / GEMINI.md are compiled from LINC.md by
# linc-sync-agents and inherit its regions — not regenerated here.
TARGET_FILES: tuple[str, ...] = ("README.md", "LINC.md")

# Display order + headings for tool modules.
_MODULE_SECTIONS: tuple[tuple[str, str], ...] = (
    ("linc_nerve.mcp.discovery_tools", "Discovery & Capabilities"),
    ("linc_nerve.mcp.screenshot_tools", "Screenshots & Streaming"),
    ("linc_nerve.mcp.ui_tools", "UI Inspection"),
    ("linc_nerve.mcp.navigation_tools", "Navigation"),
    ("linc_nerve.mcp.input_tools", "Input"),
    ("linc_nerve.mcp.app_tools", "App Management"),
    ("linc_nerve.mcp.emulator_tools", "Emulator / Simulator"),
    ("linc_nerve.mcp.recording_tools", "Recording"),
    ("linc_nerve.mcp.actionlog_tools", "Action Log"),
    ("linc_nerve.mcp.state_tools", "Device Readiness"),
    ("linc_nerve.mcp.diagnostic_tools", "Diagnostics & Observability"),
    ("linc_nerve.mcp.reservation_tools", "Reservation"),
)


def live_tool_names() -> list[str]:
    """Import all tool modules and return sorted live MCP tool names from server."""
    from linc_nerve.mcp import _core
    from linc_nerve.mcp.sse_server import _TOOL_MODULES

    for module_path in _TOOL_MODULES:
        importlib.import_module(module_path)

    tools = asyncio.run(_core.server.list_tools())
    return sorted(tool.name for tool in tools)


def _registry() -> dict[str, dict[str, str]]:
    """Import all tool modules and return the populated registry."""
    from linc_nerve.mcp import _core
    from linc_nerve.mcp.sse_server import _TOOL_MODULES

    for module_path in _TOOL_MODULES:
        importlib.import_module(module_path)
    return _core.TOOL_REGISTRY


def render_block() -> str:
    """Render the generated MCP tools section (between the block markers)."""
    registry = _registry()
    count = len(live_tool_names())

    lines: list[str] = [
        f"## MCP Tools ({count})",
        "",
        "Tools are registered via `@device_tool` (requires a device serial) or"
        " `@global_tool` (no device needed) in `src/linc_nerve/mcp/*_tools.py`."
        " This section — including the count — is generated from those"
        " registrations by `python -m linc_nerve.docs_gen`;"
        " `tests/test_docs_sync.py` fails CI when it is stale."
        " Call `nerve_capabilities` for the per-platform support matrix.",
    ]

    sectioned = {module: heading for module, heading in _MODULE_SECTIONS}
    known_modules = set(sectioned)
    by_module: dict[str, list[tuple[str, dict[str, str]]]] = {}
    for name, meta in sorted(registry.items()):
        module = meta["module"] if meta["module"] in known_modules else "other"
        by_module.setdefault(module, []).append((name, meta))

    ordered = [m for m, _ in _MODULE_SECTIONS if m in by_module]
    if "other" in by_module:
        ordered.append("other")

    for module in ordered:
        heading = sectioned.get(module, "Other")
        lines += [
            "",
            f"### {heading}",
            "",
            "| Tool | Type | Description |",
            "|------|------|-------------|",
        ]
        for name, meta in by_module[module]:
            desc = meta["description"].rstrip(".")
            lines.append(f"| `{name}` | {meta['kind']} | {desc} |")

    return "\n".join(lines)


def extract_block(text: str) -> str:
    """Return the current content between the block markers (exclusive)."""
    start = text.index(BLOCK_START) + len(BLOCK_START)
    end = text.index(BLOCK_END)
    return text[start:end].strip("\n")


def _apply(text: str, filename: str) -> str:
    """Return *text* with all generated regions rewritten."""
    if BLOCK_START not in text or BLOCK_END not in text:
        raise ValueError(f"{filename}: missing {BLOCK_START!r} / {BLOCK_END!r} markers")
    pre, rest = text.split(BLOCK_START, 1)
    _, post = rest.split(BLOCK_END, 1)
    text = f"{pre}{BLOCK_START}\n{render_block()}\n{BLOCK_END}{post}"

    count = len(live_tool_names())
    inline = re.compile(re.escape(COUNT_START) + r"\d+" + re.escape(COUNT_END))
    if not inline.search(text):
        raise ValueError(f"{filename}: missing inline {COUNT_START!r} markers")
    return inline.sub(f"{COUNT_START}{count}{COUNT_END}", text)


def check(repo_root: pathlib.Path | str) -> list[str]:
    """Return the list of TARGET_FILES whose generated regions are stale,
    and any mismatch between the tool registry and the live MCP surface."""
    root = pathlib.Path(repo_root)
    stale: list[str] = []
    for rel in TARGET_FILES:
        path = root / rel
        if not path.exists():  # the public export ships README.md but not LINC.md
            continue
        current = path.read_text(encoding="utf-8")
        if _apply(current, rel) != current:
            stale.append(rel)

    reg_names = set(_registry().keys())
    live_names = set(live_tool_names())
    if reg_names != live_names:
        reg_only = sorted(reg_names - live_names)
        live_only = sorted(live_names - reg_names)
        reg_str = ", ".join(reg_only) if reg_only else "none"
        live_str = ", ".join(live_only) if live_only else "none"
        diff_msg = (
            "Tool registry and live MCP surface differ:\n"
            f"  In registry but not live: {reg_str}\n"
            f"  In live but not registry: {live_str}"
        )
        stale.append(diff_msg)
    return stale


def write(repo_root: pathlib.Path | str) -> list[str]:
    """Rewrite stale files in place; return the list of files changed."""
    root = pathlib.Path(repo_root)
    changed: list[str] = []
    for rel in TARGET_FILES:
        path = root / rel
        if not path.exists():
            continue
        current = path.read_text(encoding="utf-8")
        regenerated = _apply(current, rel)
        if regenerated != current:
            path.write_text(regenerated, encoding="utf-8")
            changed.append(rel)
    return changed


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    repo_root = pathlib.Path(__file__).resolve().parents[2]

    if "--check" in args:
        stale = check(repo_root)
        if stale:
            mismatch_items = [
                s for s in stale if s.startswith("Tool registry and live MCP surface differ")
            ]
            for item in mismatch_items:
                print(item)
            file_stale = [
                s for s in stale if not s.startswith("Tool registry and live MCP surface differ")
            ]
            if file_stale:
                print(f"STALE generated docs: {', '.join(file_stale)}")
                print("Run: uv run python -m linc_nerve.docs_gen")
            return 1
        print("Generated docs sections are up to date.")
        return 0

    changed = write(repo_root)
    if changed:
        print(f"Regenerated: {', '.join(changed)}")
    else:
        print("Already up to date.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
